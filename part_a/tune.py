"""A2: tune the autoencoder for the REPRESENTATION, not for reconstruction (mode "tune", new in Part A).

Optuna (TPE sampler, seeded) searches SEARCH_SPACE. Every trial is one train.run_pretrain in
the proxy setting (TRAIN_PER_CLASS images per class, NUM_EPOCHS epochs) and returns the
validation k-NN top-1 accuracy, which the study maximizes. The clean validation reconstruction
MSE is stored for every trial too, for the required reconstruction-vs-k-NN plot.

Why TPE: 5 hyperparameters, one categorical with a conditional range (the noise level depends
on the corruption type), and a budget of 30 short runs. A coarse grid would need 100+ runs, and
random search ignores what earlier trials found.

The study lives in an append-only Optuna journal file under results/, so an interrupted search
loses only the running trial: run the same command again and it continues.

Outputs:
  results/pretrain_runs.csv           every trial (run_name starts with "tune/")
  results/tuning_trials.csv           Optuna's view of the study
  results/best_configs/pretrain_dae.yaml, pretrain_ae.yaml
                                      full-setting run configs built from the best trial
"""
import glob
import os

import optuna
import yaml

import config

TUNED = ("CORRUPTION", "NOISE_LEVEL", "LATENT_DIM", "LEARNING_RATE", "WEIGHT_DECAY", "RUN_NAME",
         "TRAIN_PER_CLASS", "ENCODER_PATH")


def _suggest(trial, space):
    p = {}
    p["CORRUPTION"] = trial.suggest_categorical("corruption", space["corruption"])
    if p["CORRUPTION"] == "none":
        p["NOISE_LEVEL"] = 0.0
    else:
        lo, hi = space["noise_level"][p["CORRUPTION"]]
        p["NOISE_LEVEL"] = trial.suggest_float(f"noise_level_{p['CORRUPTION']}", lo, hi)
    p["LATENT_DIM"] = trial.suggest_categorical("latent_dim", space["latent_dim"])
    p["LEARNING_RATE"] = trial.suggest_float("learning_rate", *space["learning_rate"], log=True)
    p["WEIGHT_DECAY"] = trial.suggest_float("weight_decay", *space["weight_decay"], log=True)
    return p


def _write_best_configs(best):
    out = os.path.join(config.RESULTS_DIR, "best_configs")
    os.makedirs(out, exist_ok=True)
    final = {
        "MODEL_NAME": "pretrain", "DATASET": config.DATASET, "LATENT_DIM": best["LATENT_DIM"],
        "LEARNING_RATE": best["LEARNING_RATE"], "WEIGHT_DECAY": best["WEIGHT_DECAY"],
        "NUM_EPOCHS": config.SEARCH_SPACE.get("final_epochs", 40), "BATCH_SIZE": config.BATCH_SIZE,
    }
    dae = {"RUN_NAME": "pretrain_dae", **final, "CORRUPTION": best["CORRUPTION"], "NOISE_LEVEL": best["NOISE_LEVEL"],
           "ENCODER_PATH": "checkpoints/pretrain_dae/encoder.pt"}
    # Plain counterpart: identical except q(x~|x) = identity -> lec5's plain autoencoder.
    ae = {"RUN_NAME": "pretrain_ae", **final, "CORRUPTION": "none", "NOISE_LEVEL": 0.0,
          "ENCODER_PATH": "checkpoints/pretrain_ae/encoder.pt"}
    for name, c in [("pretrain_dae", dae), ("pretrain_ae", ae)]:
        with open(os.path.join(out, f"{name}.yaml"), "w") as f:
            f.write("# Generated by tune.py from the best trial (val k-NN top-1). Copy to configs/ and commit.\n")
            yaml.safe_dump(c, f, sort_keys=False)
    print(f"Best configs written to {out}")


def run_tune():
    from train import make_datamodule, run_pretrain  # late import: train.py imports this file lazily

    space = config.SEARCH_SPACE
    os.makedirs(config.RESULTS_DIR, exist_ok=True)
    from optuna.storages import JournalStorage
    from optuna.storages.journal import JournalFileBackend, JournalFileOpenLock
    journal = os.path.join(config.RESULTS_DIR, "tune_journal.log")
    storage = JournalStorage(JournalFileBackend(journal, lock_obj=JournalFileOpenLock(journal)))
    study = optuna.create_study(study_name=config.RUN_NAME, storage=storage, direction="maximize",
                                sampler=optuna.samplers.TPESampler(seed=config.SEED), load_if_exists=True)
    if len(study.trials) == 0:  # start from the hand-picked defaults so TPE has a sane anchor
        study.enqueue_trial({"corruption": config.CORRUPTION, f"noise_level_{config.CORRUPTION}": config.NOISE_LEVEL,
                             "latent_dim": config.LATENT_DIM, "learning_rate": config.LEARNING_RATE,
                             "weight_decay": config.WEIGHT_DECAY})

    # One datamodule (the proxy subset) shared by all trials: same images, same split, same order.
    dm = make_datamodule(config.DATASET, batch_size=config.BATCH_SIZE, train_per_class=config.TRAIN_PER_CLASS,
                         drop_last=True)
    base_run = config.RUN_NAME

    def objective(trial):
        saved = {k: getattr(config, k) for k in TUNED}
        try:
            for k, v in _suggest(trial, space).items():
                setattr(config, k, v)
            config.RUN_NAME = f"tune/trial_{trial.number:03d}"
            config.ENCODER_PATH = None  # checkpoints/tune/trial_xxx/encoder.pt
            res = run_pretrain(dm=dm, logger_name=f"{base_run}/trial_{trial.number:03d}", verbose=False)
            # Trials only need their numbers; drop the heavy checkpoint files.
            for f in glob.glob(os.path.join(config.CHECKPOINT_DIR, config.RUN_NAME, "*.ckpt")):
                os.remove(f)
        finally:
            for k, v in saved.items():
                setattr(config, k, v)
        for k in ("val_recon_mse", "val_denoise_mse", "val_knn_top5", "best_epoch", "noise_level"):
            trial.set_user_attr(k, res[k])
        return res["val_knn_top1"]

    done = [t for t in study.trials if t.state == optuna.trial.TrialState.COMPLETE]
    remaining = config.N_TRIALS - len(done)
    if remaining > 0:
        study.optimize(objective, n_trials=remaining, catch=(RuntimeError,))
    study.trials_dataframe().to_csv(os.path.join(config.RESULTS_DIR, "tuning_trials.csv"), index=False)

    # The DAE is the best trial WITH a corruption. "none" trials are in the search so the sweep
    # itself shows whether corruption helps; the plain AE then gets the DAE's other settings.
    done = [t for t in study.trials if t.state == optuna.trial.TrialState.COMPLETE]
    best_trial = max((t for t in done if t.params["corruption"] != "none"), key=lambda t: t.value)
    p = best_trial.params
    best = {"CORRUPTION": p["corruption"], "NOISE_LEVEL": best_trial.user_attrs["noise_level"],
            "LATENT_DIM": p["latent_dim"], "LEARNING_RATE": p["learning_rate"], "WEIGHT_DECAY": p["weight_decay"]}
    print(f"Best DAE trial #{best_trial.number}: val k-NN top-1 = {best_trial.value:.4f}  {best}")
    print(f"Best trial overall #{study.best_trial.number}: {study.best_value:.4f} {study.best_trial.params}")
    _write_best_configs(best)
    return study
